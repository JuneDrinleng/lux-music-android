private val MorphEasing = CubicBezierEasing(0.34f, 1.56f, 0.64f, 1f)

/**
 * Play/pause button that morphs between `--fc-circle` (paused) and `--fc-cookie` (playing)
 * using the exact 108-vertex polygon coordinates from `ui/index.html`.
 */
@Composable
public fun LuxPlayButton(
    playing: Boolean,
    onClick: () -> Unit,
    modifier: Modifier = Modifier,
    size: Dp = 48.dp,
    iconSize: Dp = 26.dp,
) {
    val progress by
        animateFloatAsState(
            targetValue = if (playing) 1f else 0f,
            animationSpec = tween(durationMillis = 450, easing = MorphEasing),
            label = "playMorph",
        )
    val interaction = remember { MutableInteractionSource() }
    val pressed by interaction.collectIsPressedAsState()
    val morphShape = remember(progress) { buildMorphShape(progress) }
    val label = if (playing) "暂停" else "播放"
    Box(
        contentAlignment = Alignment.Center,
        modifier =
            modifier
                .size(size)
                .graphicsLayer {
                    translationY = if (pressed) 1.dp.toPx() else 0f
                    alpha = if (pressed) 0.96f else 1f
                }.luxDropShadow(
                    LuxShadowSpec(
                        LuxColors.ShadowLight.copy(alpha = 0.75f),
                        8.dp,
                        (-3).dp,
                        (-3).dp,
                        size / 2,
                    ),
                ).luxDropShadow(LuxShadowSpec(Color(0x38384C2E), 9.dp, 3.dp, 4.dp, size / 2))
                .clip(morphShape)
                .background(LuxBrushes.PrimaryFill)
                .semantics { contentDescription = label }
                .clickable(
                    interactionSource = interaction,
                    indication = null,
                    role = Role.Button,
                    onClick = onClick,
                ),
    ) {
        LuxIconView(
            icon = if (playing) LuxIcon.Pause else LuxIcon.Play,
            tint = LuxColors.OnAccent,
            size = iconSize,
        )
    }
}

private fun buildMorphShape(progress: Float): GenericShape =
    GenericShape { boxSize, _ ->
        val count = CirclePoly.size / 2
        for (i in 0 until count) {
            val cx = CirclePoly[i * 2]
            val cy = CirclePoly[i * 2 + 1]
            val kx = CookiePoly[i * 2]
            val ky = CookiePoly[i * 2 + 1]
            val x = (cx + (kx - cx) * progress) * boxSize.width
            val y = (cy + (ky - cy) * progress) * boxSize.height
            if (i == 0) moveTo(x, y) else lineTo(x, y)
        }
        close()
    }

